def anonymize_text(text):
    """Scrubs Windows usernames and user profile paths from stack traces and logs."""
    if not text:
        return ""
    out = str(text)
    try:
        user_profile = os.environ.get("USERPROFILE", "")
        if user_profile:
            out = out.replace(user_profile, "%USERPROFILE%")
            out = out.replace(user_profile.replace("\\", "/"), "%USERPROFILE%")
        username = os.environ.get("USERNAME", "")
        if username and len(username) >= 2:
            out = out.replace(f"\\Users\\{username}\\", "\\Users\\%USERNAME%\\")
            out = out.replace(f"/Users/{username}/", "/Users/%USERNAME%/")
    except Exception:
        pass
    return out


class CrashReporter:
    """Handles anonymized crash capture, local crash history, and mailto issue reporting."""

    def __init__(self, config=None, backend=None):
        self.config = config
        self.backend = backend
        self._installed = False

    def install_hooks(self):
        if self._installed:
            return
        self._installed = True
        ensure_local_legal_files()

        orig_excepthook = sys.excepthook

        def _custom_excepthook(exc_type, exc_value, exc_tb):
            try:
                self.record_exception(exc_type, exc_value, exc_tb, fatal=True)
            except Exception:
                pass
            if orig_excepthook:
                orig_excepthook(exc_type, exc_value, exc_tb)

        sys.excepthook = _custom_excepthook

        if hasattr(threading, "excepthook"):
            orig_thread_hook = threading.excepthook

            def _custom_thread_hook(args):
                try:
                    self.record_exception(args.exc_type, args.exc_value, args.exc_traceback, fatal=False)
                except Exception:
                    pass
                if orig_thread_hook:
                    orig_thread_hook(args)

            threading.excepthook = _custom_thread_hook

    def _collect_anonymized_specs(self):
        specs = {
            "app": f"GateFinder V{APP_VERSION}",
            "os": f"{platform.system()} {platform.release()} ({platform.version()})",
            "arch": platform.machine(),
            "python": platform.python_version(),
            "frozen": bool(getattr(sys, "frozen", False)),
        }
        try:
            if self.backend:
                fd = getattr(self.backend, "last_flight_data", None) or {}
                dep = fd.get("departure") or {}
                arr = fd.get("arrival") or {}
                specs["active_departure"] = dep.get("icao", "None")
                specs["active_arrival"] = arr.get("icao", "None")
                specs["aircraft_type"] = fd.get("aircraft", "None")
                specs["simconnect_connected"] = bool(getattr(self.backend, "sc_connected", False))
        except Exception:
            pass
        return specs

    def record_exception(self, exc_type, exc_value, exc_tb, fatal=False):
        tb_str = "".join(traceback.format_exception(exc_type, exc_value, exc_tb))
        anon_tb = anonymize_text(tb_str)
        ts = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        file_ts = datetime.now().strftime("%Y%m%d_%H%M%S")
        exc_name = getattr(exc_type, "__name__", str(exc_type))
        exc_msg = anonymize_text(str(exc_value))

        report = {
            "id": f"GF-CRASH-{file_ts}",
            "timestamp": ts,
            "fatal": bool(fatal),
            "exception_type": exc_name,
            "exception_message": exc_msg,
            "traceback": anon_tb,
            "specs": self._collect_anonymized_specs(),
        }

        try:
            cdir = get_crashes_dir()
            json_path = os.path.join(cdir, f"crash_{file_ts}.json")
            txt_path = os.path.join(cdir, f"crash_{file_ts}.txt")
            with open(json_path, "w", encoding="utf-8") as f:
                json.dump(report, f, indent=2)
            with open(txt_path, "w", encoding="utf-8") as f:
                f.write(self.format_report_text(report))
        except Exception:
            pass

        # If fatal and auto-send is enabled, prompt to send via email
        try:
            auto_send = True
            if self.config and isinstance(getattr(self.config, "settings", None), dict):
                auto_send = bool(self.config.settings.get("send_crash_reports", True))
            if fatal and auto_send:
                self.open_mailto_for_report(report)
        except Exception:
            pass
        return report

    def format_report_text(self, report):
        specs = report.get("specs") or {}
        lines = [
            f"GateFinder V{APP_VERSION} - Anonymized Diagnostic Report",
            f"Report ID: {report.get('id', 'N/A')}",
            f"Timestamp: {report.get('timestamp', 'N/A')}",
            f"OS: {specs.get('os', 'Windows')} ({specs.get('arch', '')})",
            f"SimConnect Active: {specs.get('simconnect_connected', False)}",
            f"Flight Context: {specs.get('active_departure', '----')} -> {specs.get('active_arrival', '----')} ({specs.get('aircraft_type', 'N/A')})",
            f"Exception: {report.get('exception_type', '')}: {report.get('exception_message', '')}",
            "",
            "--- Anonymized Call Stack ---",
            report.get("traceback", ""),
        ]
        return "\n".join(lines)

    def get_crash_history(self):
        reports = []
        try:
            cdir = get_crashes_dir()
            for fn in sorted(os.listdir(cdir), reverse=True):
                if fn.startswith("crash_") and fn.endswith(".json"):
                    fp = os.path.join(cdir, fn)
                    try:
                        with open(fp, "r", encoding="utf-8") as f:
                            data = json.load(f)
                        data["_file_path"] = fp
                        reports.append(data)
                    except Exception:
                        pass
        except Exception:
            pass
        return reports

    def clear_crash_history(self):
        try:
            cdir = get_crashes_dir()
            for fn in os.listdir(cdir):
                if fn.startswith("crash_"):
                    try:
                        os.remove(os.path.join(cdir, fn))
                    except Exception:
                        pass
            return True
        except Exception:
            return False

    def open_mailto_issue(self, custom_report=None):
        if custom_report:
            return self.open_mailto_for_report(custom_report)
        specs = self._collect_anonymized_specs()
        history = self.get_crash_history()
        latest_crash_snippet = "None recorded"
        if history:
            latest = history[0]
            latest_crash_snippet = (
                f"{latest.get('timestamp')} - {latest.get('exception_type')}: "
                f"{latest.get('exception_message')}\n"
                f"{(latest.get('traceback') or '')[-700:]}"
            )

        subject = f"GateFinder V{APP_VERSION} - Issue / Diagnostic Report"
        body = (
            "Please describe the issue you encountered below:\n"
            "------------------------------------------------\n\n\n"
            "--- Anonymized Diagnostic Context (Zero Personal Data) ---\n"
            f"Software: {specs.get('app')}\n"
            f"OS: {specs.get('os')} ({specs.get('arch')})\n"
            f"SimConnect Connected: {specs.get('simconnect_connected')}\n"
            f"Active Context: {specs.get('active_departure')} -> {specs.get('active_arrival')} | Aircraft: {specs.get('aircraft_type')}\n"
            f"Latest Recorded Exception: {latest_crash_snippet}\n"
        )
        mailto_url = f"mailto:{SUPPORT_EMAIL}?subject={quote(subject)}&body={quote(body)}"
        try:
            os.startfile(mailto_url)
        except Exception:
            try:
                webbrowser.open(mailto_url)
            except Exception:
                pass

    def open_mailto_for_report(self, report):
        subject = f"GateFinder V{APP_VERSION} Crash Report [{report.get('id', 'DIAG')}]"
        body = self.format_report_text(report)[:1800]
        mailto_url = f"mailto:{SUPPORT_EMAIL}?subject={quote(subject)}&body={quote(body)}"
        try:
            os.startfile(mailto_url)
        except Exception:
            try:
                webbrowser.open(mailto_url)
            except Exception:
                pass


class LegacyMigrationManager:
    """
    Detects, migrates settings from, and cleanly uninstalls legacy GateFinder V1.x installations
    (such as 'wildbill75-gatefinder' in MSFS Community, old exe.xml paths, and old V1 folders)
    so users upgrading to V2.0 have a completely seamless experience.
    """

    def __init__(self, config, autostart_mgr=None):
        self.config = config
        self.autostart = autostart_mgr

    def run_startup_migration(self):
        """
        Executed automatically on startup:
        1. Finds any legacy V1.x installation paths from exe.xml or sibling directories.
        2. Migrates user settings (simbrief_username, gsx_profile_path, community paths) if not yet configured in V2.0.
        3. Removes legacy 'wildbill75-gatefinder' Community packages and installs 'gatefinder-ingame-panel' in their place.
        4. Updates any legacy exe.xml <Launch.Addon> entries pointing to old V1.x GateFinder.exe paths so MSFS launches V2.0.
        Returns a summary dict of actions taken.
        """
        import shutil
        import xml.etree.ElementTree as ET
        from config import find_all_possible_community_folders

        summary = {
            "migrated_settings_from": None,
            "removed_legacy_packages": [],
            "installed_v2_packages": [],
            "updated_exe_xml_files": [],
            "legacy_app_folders_found": [],
        }

        if getattr(sys, "frozen", False):
            current_exe_dir = os.path.normpath(os.path.dirname(os.path.abspath(sys.executable)))
            current_exe_path = os.path.normpath(os.path.abspath(sys.executable))
        else:
            current_exe_dir = os.path.normpath(os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))
            current_exe_path = os.path.normpath(os.path.abspath(sys.argv[0]))

        candidate_legacy_dirs = []

        # 1. Inspect all MSFS exe.xml files for old GateFinder paths
        exe_xml_paths = self.autostart.get_all_exe_xml_paths() if self.autostart else []
        for xml_p in exe_xml_paths:
            try:
                tree = ET.parse(xml_p)
                root = tree.getroot()
                modified = False
                for launch in root.findall("Launch.Addon"):
                    name_node = launch.find("Name")
                    path_node = launch.find("Path")
                    name_text = name_node.text.strip() if (name_node is not None and name_node.text) else ""
                    path_text = path_node.text.strip() if (path_node is not None and path_node.text) else ""
                    if name_text in ("GSX GateFinder", "GateFinder") or "gatefinder.exe" in path_text.lower():
                        if path_text:
                            old_exe_norm = os.path.normpath(path_text)
                            old_dir_norm = os.path.normpath(os.path.dirname(old_exe_norm))
                            if old_dir_norm.lower() != current_exe_dir.lower():
                                if os.path.isdir(old_dir_norm) and old_dir_norm not in candidate_legacy_dirs:
                                    candidate_legacy_dirs.append(old_dir_norm)
                                # Update exe.xml entry to point to V2.0 executable
                                if getattr(sys, "frozen", False):
                                    path_node.text = current_exe_path
                                    if name_node is not None:
                                        name_node.text = "GateFinder"
                                    modified = True
                if modified:
                    tree = ET.ElementTree(root)
                    ET.indent(tree, space="  ", level=0)
                    tree.write(xml_p, encoding="Windows-1252", xml_declaration=True)
                    summary["updated_exe_xml_files"].append(xml_p)
                    if not self.config.settings.get("auto_start"):
                        self.config.settings["auto_start"] = True
            except Exception as e:
                print(f"[Migration] Error inspecting {xml_p}: {e}")

        # 2. Also check sibling directories for older GateFinder folders
        try:
            parent_dir = os.path.dirname(current_exe_dir)
            if parent_dir and os.path.isdir(parent_dir):
                sib_candidates = []
                for entry in os.listdir(parent_dir):
                    full_sib = os.path.normpath(os.path.join(parent_dir, entry))
                    if full_sib.lower() == current_exe_dir.lower() or not os.path.isdir(full_sib):
                        continue
                    el = entry.lower()
                    sib_cfg = os.path.join(full_sib, "settings.json")
                    if ("gatefinder" in el or "gsx_gatefinder" in el) and os.path.exists(sib_cfg):
                        try:
                            mtime = os.path.getmtime(sib_cfg)
                        except Exception:
                            mtime = 0.0
                        sib_candidates.append((mtime, full_sib))
                sib_candidates.sort(key=lambda x: x[0], reverse=True)
                for _, full_sib in sib_candidates:
                    if full_sib not in candidate_legacy_dirs:
                        candidate_legacy_dirs.append(full_sib)
                parent_cfg = os.path.join(parent_dir, "settings.json")
                if os.path.isfile(parent_cfg) and parent_dir.lower() != current_exe_dir.lower():
                    if parent_dir not in candidate_legacy_dirs:
                        candidate_legacy_dirs.append(parent_dir)
        except Exception:
            pass

        summary["legacy_app_folders_found"] = list(candidate_legacy_dirs)

        # 3. Migrate settings and scenery cache from previous installation if V2 has no SimBrief username yet
        if not self.config.settings.get("simbrief_username", "").strip():
            for ldir in candidate_legacy_dirs:
                legacy_cfg_path = os.path.join(ldir, "settings.json")
                if os.path.isfile(legacy_cfg_path):
                    try:
                        with open(legacy_cfg_path, "r", encoding="utf-8") as f:
                            old_data = json.load(f)
                        changed = False
                        for key in ("simbrief_username", "gsx_profile_path", "msfs_community_path", "msfs_community2024_path", "sayintentions_api_key"):
                            val = str(old_data.get(key, "")).strip()
                            if val and not str(self.config.settings.get(key, "")).strip():
                                self.config.settings[key] = val
                                changed = True
                        for bkey in (
                            "auto_start", "auto_fetch", "mars_overlap_protection",
                            "prioritize_ai_atc", "auto_inject_gsx", "gsx_request_follow_me",
                            "check_online_traffic", "auto_lock_turnaround", "auto_clear_ai",
                            "hibernate_map_in_flight", "send_crash_reports", "share_flight_stats",
                        ):
                            if bkey in old_data and isinstance(old_data[bkey], bool):
                                self.config.settings[bkey] = old_data[bkey]
                                changed = True
                        if changed:
                            self.config.save()
                            summary["migrated_settings_from"] = legacy_cfg_path
                            # Also copy local scenery cache files if missing in the new folder
                            try:
                                old_cache_dir = os.path.join(ldir, "cache")
                                new_cache_dir = os.path.join(current_exe_dir, "cache")
                                if os.path.isdir(old_cache_dir):
                                    os.makedirs(new_cache_dir, exist_ok=True)
                                    for cfile in ("scenery_fingerprints.json", "scenery_gates_cache.json", "session_state.json"):
                                        src_cf = os.path.join(old_cache_dir, cfile)
                                        dst_cf = os.path.join(new_cache_dir, cfile)
                                        if os.path.isfile(src_cf) and not os.path.exists(dst_cf):
                                            shutil.copy2(src_cf, dst_cf)
                                src_tc = os.path.join(ldir, "taxi_charts_cache.json")
                                dst_tc = os.path.join(current_exe_dir, "taxi_charts_cache.json")
                                if os.path.isfile(src_tc) and not os.path.exists(dst_tc):
                                    shutil.copy2(src_tc, dst_tc)
                            except Exception:
                                pass
                            break
                    except Exception:
                        pass

        # 4. Scan all Community folders for legacy 'wildbill75-gatefinder' and upgrade to 'gatefinder-ingame-panel'
        comm_dirs = set()
        for k in ("msfs_community_path", "msfs_community2024_path"):
            val = self.config.settings.get(k, "")
            for p in str(val).split(";"):
                if p.strip() and os.path.isdir(p.strip()):
                    comm_dirs.add(os.path.normpath(p.strip()))
        for p in find_all_possible_community_folders():
            if p and os.path.isdir(p):
                comm_dirs.add(os.path.normpath(p))
        for cdir in list(comm_dirs):
            parent = os.path.dirname(cdir)
            if parent and os.path.isdir(parent):
                for sib in ("Community", "Community2024", "Community2020"):
                    sp = os.path.join(parent, sib)
                    if os.path.isdir(sp):
                        comm_dirs.add(os.path.normpath(sp))

        # Locate the new V2.0 package source
        src_v2_pkg = None
        for cand in [
            os.path.join(current_exe_dir, "MSFS_Package", PANEL_PACKAGE_NAME),
            os.path.join(current_exe_dir, PANEL_PACKAGE_NAME),
            os.path.join(getattr(sys, "_MEIPASS", ""), "MSFS_Package", PANEL_PACKAGE_NAME) if hasattr(sys, "_MEIPASS") else "",
        ]:
            if cand and os.path.isdir(cand):
                src_v2_pkg = cand
                break

        for cdir in comm_dirs:
            had_legacy = False
            for legacy_name in LEGACY_PACKAGE_NAMES:
                legacy_p = os.path.join(cdir, legacy_name)
                if os.path.exists(legacy_p) or os.path.islink(legacy_p):
                    try:
                        if os.path.islink(legacy_p):
                            os.unlink(legacy_p)
                        elif os.path.isdir(legacy_p):
                            try:
                                os.rmdir(legacy_p)
                            except OSError:
                                shutil.rmtree(legacy_p)
                        else:
                            os.remove(legacy_p)
                        summary["removed_legacy_packages"].append(legacy_p)
                        had_legacy = True
                    except Exception as e:
                        print(f"[Migration] Could not remove legacy package {legacy_p}: {e}")

            # If this Community folder had the legacy panel installed, automatically install the new V2.0 panel!
            if had_legacy and src_v2_pkg:
                new_p = os.path.join(cdir, PANEL_PACKAGE_NAME)
                try:
                    shutil.copytree(src_v2_pkg, new_p, dirs_exist_ok=True)
                    summary["installed_v2_packages"].append(new_p)
                except Exception as e:
                    print(f"[Migration] Could not install V2 panel to {new_p}: {e}")

        return summary
