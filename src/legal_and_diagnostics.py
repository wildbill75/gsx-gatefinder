def _format_sections_plain(header_title, header_sub, header_intro, sections):
    lines = [
        "=" * 78,
        header_title,
        header_sub,
        "=" * 78,
        "",
        header_intro,
        "",
    ]
    for sec_title, items in sections:
        lines.append("-" * 78)
        lines.append(sec_title)
        lines.append("-" * 78)
        for label, body in items:
            if label:
                lines.append(f"{label} {body}")
            else:
                lines.append(body)
            lines.append("")
    lines.append(f"© 2026 {AUTHOR_NAME} • {SUPPORT_EMAIL}")
    return "\n".join(lines)


